win_ok() {
  [[ "$1" =~ ^[0-9]{4}-[0-9]{2}-[0-9]{2}$ ]] || return 1
  [[ "$2" =~ ^([0-2][0-9]:[0-5][0-9])-([0-2][0-9]:[0-5][0-9])$ ]] || return 1
  local a=${BASH_REMATCH[1]} b=${BASH_REMATCH[2]}
  [[ ! "$a" > "$b" ]] || return 1
  [ "$3" = "$1" ] || return 1
  [[ "$4" =~ ^[0-2][0-9]:[0-5][0-9]$ ]] || return 1
  [[ ! "$4" < "$a" && ! "$4" > "$b" ]]
}
