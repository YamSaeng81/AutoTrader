-- 철회의 정당성과 실패 사유를 구분한다 (2026-10-12)
--
-- ■ 고치는 문제 1 — 철회가 시간으로 정당화되고 있었다
--
-- V84 의 복구는 `INTENT_READY` 가 60초를 넘으면 철회했다. 조건부 전환(`WHERE state='INTENT_READY'`)
-- 은 claim 과의 **경합**을 해결하지만, 철회가 **정당한지**는 결정하지 않는다. 오래 걸렸을 뿐 살아
-- 있는 정상 대기 주문도 철회가 먼저 성립하면 취소됐다 — 시간 기반 철회였다.
--
-- 이제 철회는 **그 의도를 claim 할 작업자가 더 이상 존재하지 않음이 확정될 때만** 정당하다:
--
--   WITHDRAWN_STOPPED        claim 직전, 세션 행 잠금 안에서 정지를 확인했다 (작업자 자신이 판단)
--   WITHDRAWN_OWNER_LOST     의도를 만든 프로세스가 지금 프로세스가 아니다 (재기동 — 그 작업 큐는
--                            프로세스와 함께 사라졌다)
--   WITHDRAWN_DISPATCH_LOST  같은 프로세스지만 그 의도를 맡은 작업이 더는 없다 (디스패치 거절·
--                            claim 전 예외로 작업이 끝났다)
--
-- 경과 시간은 **경보에만** 쓴다. 살아 있는 작업자가 맡은 의도는 얼마나 오래됐든 철회하지 않는다.
--
-- 🔴 전제: **애플리케이션 인스턴스는 하나다.** 소유자가 지금 프로세스가 아니면 죽은 것으로 본다.
--    인스턴스를 여러 개 띄우면 이 판단이 틀린다 — 그때는 소유자 생존 신호(heartbeat)가 필요하다.
--    (폴러·스케줄러 전체가 이미 단일 인스턴스를 전제한다.)
--
-- ■ 고치는 문제 2 — FAILED 가 두 가지 뜻을 가졌다
--
-- "거래소가 명시적으로 거절했다" 와 "우리가 내보내지 않고 철회했다" 가 같은 `FAILED` 였다. 둘 다
-- "나간 돈이 없다" 는 점은 같아 복원 경로는 그대로 쓰지만, **근거가 다르다** — 앞의 것은 거래소의
-- 진술이고 뒤의 것은 우리의 불변식(claim 이 없었다)이다. 사람이 보거나 사후 대조할 때 섞이면 안 된다.
--
-- 상태를 늘리지 않고 사유 코드로 구분한다. `FAILED` 를 "체결 없이 종결" 로 읽는 복원 경로가 12곳
-- 이상이라, 상태를 쪼개면 그 전부를 바꿔야 하고 하나라도 빠지면 자금이 묶인다.
--
-- 🔴 현재 제출 경로는 **거래소의 명시적 거절을 FAILED 로 기록하지 않는다.** 제출 중 예외는 HTTP 4xx
--    를 포함해 전부 `UNKNOWN` 이다(구분하지 않고 더 위험한 쪽으로 가정). 따라서 지금 `FAILED` 는
--    거래소 거절을 주장하는 일이 없다. `EXCHANGE_REJECTED` 는 그 분류를 구현할 때를 위해 자리만 둔다.

ALTER TABLE "order"
    ADD COLUMN IF NOT EXISTS failure_code VARCHAR(40);

COMMENT ON COLUMN "order".failure_code IS
    'FAILED 의 근거. WITHDRAWN_* = 내보내지 않고 철회(우리 불변식), RISK_REJECTED·CLIENT_UNAVAILABLE = 의도 단계 거절, EXCHANGE_REJECTED = 거래소의 명시적 거절(현재 미사용). NULL = V86 이전.';

ALTER TABLE "order"
    ADD COLUMN IF NOT EXISTS intent_owner VARCHAR(64);

COMMENT ON COLUMN "order".intent_owner IS
    '의도를 만든 프로세스의 식별자(기동마다 새로 생성). 복구는 소유자가 지금 프로세스가 아닐 때만 미claim 의도를 철회한다 — 단일 인스턴스 전제.';
