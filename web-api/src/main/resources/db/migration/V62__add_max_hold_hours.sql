-- V62: 동적 세션에 최대 보유시간(time stop) 추가
--
-- 배경 (2026-07-31 운영 분석):
--   세션 38의 KRW-RLUSD 포지션이 42시간째 청산되지 않고 고착됐다. RLUSD는 리플의 USD
--   스테이블코인이라 KRW 환산 변동성이 사실상 0에 가깝고, SL(-5%)·TP(+10%) 어느 쪽도
--   도달하지 못한다. 청산 조건이 전부 "가격 기반"이라 시간이 아무리 흘러도 빠져나올
--   경로가 없었고, 세션 자본 8,000원이 무기한 잠겼다.
--
--   전략 SELL 경로도 구제책이 되지 못한다 — MIN_HOLD_MINUTES(180분) 통과 후에도
--   "수익 0.3% 이상" 조건이 붙어 있어, 변동이 없는 종목은 영원히 SELL 신호가 나지 않는다.
--
-- 기본 24시간: 동적 세션은 워치리스트를 순회하며 기회를 찾는 구조라, 하루가 지나도
--   방향이 나오지 않은 포지션은 자본 회전을 막는 기회비용이 손실보다 크다.
--   (2026-07-31 실측 평균 보유시간 7.6시간 — 정상 매매는 24시간에 한참 못 미친다)

ALTER TABLE dynamic_session
    ADD COLUMN max_hold_hours INT NOT NULL DEFAULT 24;

COMMENT ON COLUMN dynamic_session.max_hold_hours IS
    '최대 보유시간(시). 초과 시 손익과 무관하게 시장가 청산 — 저변동 종목 고착 방지. 0 이하면 비활성.';
