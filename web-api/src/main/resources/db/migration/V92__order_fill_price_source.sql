-- 페이퍼 체결가의 출처 (2026-10-15 리뷰 8회차)
--
-- 페이퍼(DYNAMIC 페이퍼 모드) 체결가는 관측 가격이 아니라 시뮬레이션 가정이다. 종전에는 "신호가 NULL" 로 가정 체결을 가려내려
-- 했지만 그 조건은 정확하지 않다 — 정지 청산은 평균 단가를 신호가 자리에 넣어 NULL 이 아니고, 실주문 경로·과거 행에도 NULL 이
-- 있을 수 있다. 출처를 명시적으로 남긴다.
--
--   PAPER_SIGNAL    신호가(그 회차의 판정 가격 — 캔들 종가 또는 유효한 실시간 시세)에 슬리피지를 넣은 가정 체결
--   PAPER_LAST_MARK 신호가가 없어 마지막으로 받은 시세(나이 무관)로 정한 가정 체결
--   PAPER_AVG_PRICE 평균 단가로 정한 가정 체결 — 그 값에 팔 수 있었다는 근거가 아니다
--   NULL            기록 없음: 실주문(거래소 보고 체결)이거나 이 열 이전의 행
ALTER TABLE "order" ADD COLUMN fill_price_source VARCHAR(20);
